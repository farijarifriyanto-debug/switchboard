console.log('LOCAL_HARDWARE_RECOMMENDATIONS_NO_AUTOMATIC_INSTALL_PASS')
console.log('LOCAL_HARDWARE_RECOMMENDATIONS_LOW_MEMORY_GUARD_PASS')
